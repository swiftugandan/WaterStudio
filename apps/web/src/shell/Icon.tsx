/** Resolves an icon name from a command to the hydraulic set or a Lucide icon. */

import { HydraulicIcon, hydraulicIconNames, type HydraulicIconName } from '@waterstudio/ui';
import {
  ArrowLeftRight,
  ChartColumn,
  ChartLine,
  Command,
  FileInput,
  FileOutput,
  FileText,
  Globe,
  Image,
  ImageOff,
  Map as MapIcon,
  Mountain,
  FilePlus,
  FolderOpen,
  Hand,
  Monitor,
  Moon,
  MousePointer2,
  PanelsTopLeft,
  Redo2,
  Rows3,
  Save,
  Scan,
  Settings,
  Sparkles,
  Spline,
  Layers,
  Search,
  Type,
  Plus,
  Ruler,
  Printer,
  Palette,
  Copy,
  Clipboard,
  Hash,
  Flame,
  FlaskConical,
  ArrowRight,
  Filter,
  ListChecks,
  SquareDashedMousePointer,
  StepBack,
  StepForward,
  Sun,
  SunMoon,
  Trash2,
  Undo2,
  X,
  ZoomIn,
  ZoomOut,
  Maximize,
  type LucideIcon,
} from 'lucide-react';

const LUCIDE: Record<string, LucideIcon> = {
  flask: FlaskConical,
  'file-plus': FilePlus,
  'folder-open': FolderOpen,
  save: Save,
  undo: Undo2,
  redo: Redo2,
  trash: Trash2,
  'select-all': SquareDashedMousePointer,
  x: X,
  pointer: MousePointer2,
  hand: Hand,
  fit: Maximize,
  'zoom-in': ZoomIn,
  'zoom-out': ZoomOut,
  scan: Scan,
  sparkles: Sparkles,
  command: Command,
  moon: Moon,
  sun: Sun,
  'sun-moon': SunMoon,
  rows: Rows3,
  monitor: Monitor,
  panel: PanelsTopLeft,
  'step-back': StepBack,
  'step-forward': StepForward,
  'chart-line': ChartLine,
  'chart-column': ChartColumn,
  mountain: Mountain,
  'arrow-left-right': ArrowLeftRight,
  'file-text': FileText,
  'file-input': FileInput,
  'file-output': FileOutput,
  globe: Globe,
  image: Image,
  'image-off': ImageOff,
  map: MapIcon,
  settings: Settings,
  spline: Spline,
  'list-checks': ListChecks,
  layers: Layers,
  search: Search,
  type: Type,
  plus: Plus,
  ruler: Ruler,
  printer: Printer,
  palette: Palette,
  copy: Copy,
  clipboard: Clipboard,
  hash: Hash,
  flame: Flame,
  'arrow-right': ArrowRight,
  filter: Filter,
};

const HYDRAULIC = new Set<string>(hydraulicIconNames);

export function Icon({ name, size = 16 }: { name: string | undefined; size?: number }) {
  if (name && HYDRAULIC.has(name)) return <HydraulicIcon name={name as HydraulicIconName} size={size} />;
  const L = name ? LUCIDE[name] : undefined;
  return L ? <L size={size} aria-hidden="true" strokeWidth={size >= 24 ? 1.75 : 2} /> : null;
}
