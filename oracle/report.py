#!/usr/bin/env python3
"""Render docs/PARITY.md from the native and WebAssembly comparison reports.

usage: report.py <native.json> <wasm.json> > docs/PARITY.md
"""

import json
import sys


def fmt(x):
    return "" if x is None else f"{x:.1e}"


def main():
    native = {r["network"]: r for r in json.load(open(sys.argv[1]))}
    wasm = {r["network"]: r for r in json.load(open(sys.argv[2]))}
    names = sorted(native)
    n_ok = sum(native[n]["status"] == "ok" for n in names)
    w_ok = sum(wasm.get(n, {}).get("status") == "ok" for n in names)

    out = [
        "# Engine parity with OWA-EPANET",
        "",
        "Generated by `oracle/parity.sh --write-doc`; do not edit by hand.",
        "",
        f"Reference: OWA-EPANET v2.3.5. Corpus: {len(names)} hydraulic networks "
        "(OWA's epanet-example-networks and Net1-Net3).",
        "",
        f"**Within tolerance: native {n_ok}/{len(names)}, WebAssembly {w_ok}/{len(names)}.**",
        "",
        "Tolerances: head within 0.001 ft (0.0003 m), and flow and demand within 0.01 % or 0.001 flow units,",
        "at every report step. The reference's binary output holds 32-bit floats, which sets a floor near",
        "1e-5 relative.",
        "",
        "| Network | Native | WebAssembly | Max head error | Max flow error | Nodes | Links |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    order = sorted(names, key=lambda n: (native[n]["status"] == "ok", n))
    for n in order:
        r, w = native[n], wasm.get(n, {})
        out.append(f"| {n} | {r['status']} | {w.get('status', 'missing')} | {fmt(r.get('max_head_err'))} | "
                   f"{fmt(r.get('max_flow_err'))} | {r.get('nodes', '')} | {r.get('links', '')} |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
